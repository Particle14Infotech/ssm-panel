function generateCssVariables() {
  const lightVars = Object.entries(tokens.light)
    .map(([key, value]) => `    --${key}: ${value};`)
    .join("\n");

  const darkVars = Object.entries(tokens.dark)
    .map(([key, value]) => `    --${key}: ${value};`)
    .join("\n");

  const radiiVars = Object.entries(tokens.radii)
    .map(([key, value]) => `    --radius-${key}: ${value};`)
    .join("\n");

  return `
/* AUTOGENERATED FROM @smm/ui tokens.js - DO NOT EDIT MANUALLY */
:root {
${lightVars}
${radiiVars}
}

.dark, [data-theme="dark"] {
${darkVars}
}
`;
}

